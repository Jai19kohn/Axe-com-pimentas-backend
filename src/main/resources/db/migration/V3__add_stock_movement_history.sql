CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    movement_type VARCHAR(20) NOT NULL,
    quantity_delta INTEGER NOT NULL,
    resulting_quantity INTEGER NOT NULL,
    reason VARCHAR(500) NOT NULL,
    reference VARCHAR(120),
    responsible VARCHAR(120) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    idempotency_key UUID NOT NULL UNIQUE,
    CONSTRAINT ck_stock_movements_type CHECK (movement_type IN ('RECEIPT', 'ISSUE', 'ADJUSTMENT', 'DAMAGE')),
    CONSTRAINT ck_stock_movements_delta CHECK (quantity_delta <> 0),
    CONSTRAINT ck_stock_movements_resulting_quantity CHECK (resulting_quantity >= 0)
);

CREATE INDEX ix_stock_movements_product_occurred_at
    ON stock_movements (product_id, occurred_at DESC, id DESC);
