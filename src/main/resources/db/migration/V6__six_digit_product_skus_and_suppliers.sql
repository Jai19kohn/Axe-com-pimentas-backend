DO $$
BEGIN
    IF (SELECT COUNT(*) FROM products) > 999999 THEN
        RAISE EXCEPTION 'Cannot migrate more than 999999 products to six-digit SKUs';
    END IF;
END
$$;

CREATE SEQUENCE product_sku_seq START WITH 1 MAXVALUE 999999;

UPDATE products SET sku = '__MIGRATION__' || id;

WITH ordered_products AS (
    SELECT id, LPAD(nextval('product_sku_seq')::TEXT, 6, '0') AS new_sku
    FROM products
    ORDER BY id
)
UPDATE products p
SET sku = ordered_products.new_sku
FROM ordered_products
WHERE p.id = ordered_products.id;

SELECT setval(
    'product_sku_seq',
    COALESCE((SELECT MAX(sku::INTEGER) FROM products), 1),
    EXISTS (SELECT 1 FROM products)
);

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO suppliers (name)
SELECT MIN(BTRIM(supplier))
FROM products
WHERE supplier IS NOT NULL AND BTRIM(supplier) <> ''
GROUP BY LOWER(BTRIM(supplier));

CREATE UNIQUE INDEX uq_suppliers_name_ci ON suppliers (LOWER(name));

ALTER TABLE products ADD COLUMN supplier_id BIGINT REFERENCES suppliers(id);

UPDATE products p
SET supplier_id = s.id
FROM suppliers s
WHERE p.supplier IS NOT NULL
  AND LOWER(BTRIM(p.supplier)) = LOWER(s.name);

ALTER TABLE products DROP COLUMN supplier;
ALTER TABLE products DROP COLUMN physical_location;
